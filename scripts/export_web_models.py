"""Export data the web app needs from the Python reference implementation.

Writes two generated files under web/src/models/:

- qrisk3Coefficients.ts: QRISK3 tables, so TypeScript and Python share one source.
- parity.fixture.json: random profiles scored by Python, which the TypeScript
  tests must reproduce.

Usage: python scripts/export_web_models.py
"""

from __future__ import annotations

import json
from dataclasses import fields
from pathlib import Path
from typing import get_args

import numpy as np

from heartrisk import Profile, score
from heartrisk.models.qrisk3 import _COEFFICIENTS
from heartrisk.profile import Diabetes, Ethnicity, Smoking

OUT = Path(__file__).parents[1] / "web" / "src" / "models"
CONDITIONS = [
    "atrial_fibrillation",
    "atypical_antipsychotics",
    "corticosteroids",
    "erectile_dysfunction",
    "migraine",
    "rheumatoid_arthritis",
    "chronic_kidney_disease",
    "severe_mental_illness",
    "lupus",
]

HEADER = """\
// SPDX-License-Identifier: LGPL-3.0-or-later
//
// QRISK3-2017 coefficients. Copyright 2017 ClinRisk Ltd. (https://qrisk.org),
// released under the GNU Lesser General Public License v3 or later.
//
// GENERATED by scripts/export_web_models.py from src/heartrisk/models/qrisk3.py.
// Do not edit by hand.
"""


def camel(name: str) -> str:
    head, *rest = name.split("_")
    return head + "".join(part.title() for part in rest)


def coefficients_ts() -> str:
    tables = {
        "female" if female else "male": {camel(k): v for k, v in table.items()}
        for female, table in _COEFFICIENTS.items()
    }
    body = json.dumps(tables, indent=2)
    return f"{HEADER}\nexport const QRISK3_COEFFICIENTS = {body} as const;\n"


def random_profile(rng: np.random.Generator) -> Profile:
    total = float(rng.uniform(140, 300))
    return Profile(
        age=float(rng.integers(30, 80)),
        sex=str(rng.choice(["female", "male"])),
        ethnicity=str(rng.choice(get_args(Ethnicity))),
        total_cholesterol=round(total),
        hdl_cholesterol=round(float(rng.uniform(25, min(95, total - 40)))),
        systolic_bp=round(float(rng.uniform(95, 195))),
        on_bp_meds=bool(rng.random() < 0.3),
        smoking=str(rng.choice(get_args(Smoking))),
        diabetes=str(rng.choice(get_args(Diabetes))),
        bmi=round(float(rng.uniform(19, 39)), 1),
        egfr=round(float(rng.uniform(20, 130))),
        on_statin=bool(rng.random() < 0.2),
        family_history_cvd=bool(rng.random() < 0.3),
        systolic_bp_sd=None if rng.random() < 0.5 else round(float(rng.uniform(2, 25)), 1),
        townsend=round(float(rng.uniform(-5, 8)), 2),
        **{c: bool(rng.random() < 0.1) for c in CONDITIONS},
    )


def parity_json(n: int = 300) -> str:
    rng = np.random.default_rng(2790)
    cases = []
    for _ in range(n):
        p = random_profile(rng)
        cases.append(
            {
                "profile": {camel(f.name): getattr(p, f.name) for f in fields(p)},
                "risk": {k: r.risk for k, r in score(p).items()},
            }
        )
    return json.dumps(cases, indent=1) + "\n"


GENERATED = {"qrisk3Coefficients.ts": coefficients_ts, "parity.fixture.json": parity_json}


if __name__ == "__main__":
    for name, build in GENERATED.items():
        (OUT / name).write_text(build())
    print(f"Wrote {OUT / 'qrisk3Coefficients.ts'} and {OUT / 'parity.fixture.json'}")
